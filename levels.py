H = 15

def build(ground, features):
    w = len(ground)
    grid = [[0] * w for _ in range(H)]
    for col, gh in enumerate(ground):
        for row in range(H - gh, H):
            grid[row][col] = GROUND
    player_start = None
    exit_pos = None
    enemies = []
    for fx, fy, ft in features:
        if ft == 'P':
            player_start = (fx, fy)
        elif ft == 'E':
            exit_pos = (fx, fy)
            grid[fy][fx] = EXIT
        elif ft == ENEMY:
            enemies.append((fx, fy))
        else:
            if 0 <= fy < H and 0 <= fx < w:
                grid[fy][fx] = ft
    if not player_start:
        player_start = (0, H - 2)
    return grid, player_start, exit_pos, enemies

def count(grid):
    return sum(row.count(STRAWBERRY) for row in grid)

